/** 策略 2（quality_policy_version=2）职责提示。历史“三次接管/两阶段计数/测试改代码再复核”不再适用。 */
export function roleBoundaryInstructionsFor(purpose: string): string {
  switch (purpose) {
    case "quality_review":
      return (
        "本轮只做代码质量复核：只判断本任务相关代码质量；默认接受自测说明；不核验测试真实性。" +
        "无必需修改的问题就通过；建议项不得伪装成阻塞问题。首次失败请给出可执行的详细整改报告。" +
        "历史“三次整改”“两阶段独立计数”不适用于本轮。"
      );
    case "planner_takeover":
      return (
        "本轮是规划质量修复：实际修改代码并阅读修改后的代码完成自查。" +
        "不运行测试、构建、lint、typecheck 或任何测试证明脚本；可以修改相关测试源码。" +
        "把相关回归关注点写入摘要交执行模型。完成后报告 completed，不表示测试已完成。"
      );
    case "executor_test":
      return (
        "本轮是执行测试：负责必要测试、构建和静态检查；修复测试暴露的本任务相关小问题并重测。" +
        "完成后直接交人工或规划提交，不请求新一轮规划复核，不做测试真实性证明。" +
        "修改说明写入摘要即可；平台不根据代码变更追加关卡。"
      );
    case "planner_commit":
      return (
        "本轮只执行提交工作：只暂存并提交本任务范围内代码，保留他人修改和已有 index 内容。" +
        "integration_repair 中的所有提交问题由你继续解决，不只处理代码冲突。合并固定目标提交并保留双方有效行为与历史；处理源工作区问题时，只操作登记的源工作区，先保存可恢复的文件与 index，保留他人的修改、未跟踪文件和暂存边界，不提交无关修改、不覆盖并发改动。禁止整文件选择 ours/theirs、reset --hard、clean 或丢弃历史。" +
        "解决冲突所必需的代码调整和受影响的定向验证属于本轮提交收尾，完成后返回包含双方提交的新提交号。不重开开发、全量测试或泛化复核，不顺手修无关代码，不把未执行的验证说成通过。" +
        "任何无法自行安全解决的问题，包括权限、锁、仓库丢失、未提交内容保留或业务取舍，都返回 need_user，同时提供 user_interaction，明确问题、选项、影响和用户操作步骤，由确认弹窗收集答复后继续同一提交阶段。requires_user 为 true 时必须提出具体问题，不能重复失败操作或报告完成。"
      );
    case "functional_fix":
      return (
        "本轮处理人工验收阶段的用户指导。先响应本轮指导原文，说明将做什么，再按用户实际要求执行；内部用途名 functional_fix 不代表每次指导都要求修改代码或重新测试。" +
        "用户要求修复功能时，定位并修复该问题，完成受影响的必要测试，再交人工复测；保留原有代码复核流程，不能代人关闭问题或确认验收通过。" +
        "用户只要求启动或准备验收环境时，沿用已有工作区和成果启动所需服务，核实可访问，返回实际地址与端口并保留服务供用户操作；完成本轮指导即可报告 completed，回到人工验收。指导同时包含问题、操作或测试要求时逐项回答并落实，不能把整条指导归成启动服务而忽略其余内容。" +
        "不因进入本轮而重新开发、重跑整套测试或重复完成已完成的计划；落实用户明确要求的测试和实际代码修改所需回归，未受影响的结果继续复用。用户追问是否做过测试时如实回答已做、未做或无法确认，不以新启动测试代替回答。" +
        "skill_resources 中执行与测试规则在落实本轮指导涉及相关开发或测试时参考；不能覆盖用户原文。仅启动验收环境不自动重跑整套测试，但用户要求补做的 OpenTabs 真实浏览器测试必须实际落实，不能用 E2E 结果替代。" +
        "保留批准范围、用户权限和原工作区、原会话，不另建替代计划。" +
        acceptancePreparationInstructions
      );
    default:
      return (
        "当前用途指令优先。历史“三次接管”“规划接管后完整测试”“测试改了代码就再复核”不覆盖当前用途。" +
        "所有测试归执行模型；规划修复不跑测试；测试完成后按人工前/后阶段直接进入下一步。"
      );
  }
}

